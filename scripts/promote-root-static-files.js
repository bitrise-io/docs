#!/usr/bin/env node
/**
 * Copies special root-level files (_redirects, _headers, robots.txt,
 * sitemap.xml, 404.html) up from the default locale's per-locale output
 * directory to the true build root.
 *
 * Since i18n.localeConfigs[locale].baseUrl gave each locale its own baseUrl
 * (see docusaurus.config.ts), Docusaurus now writes every locale's copy of
 * these files under its own subdirectory (build/en/_redirects,
 * build/ja/_redirects, ...), never at build/ itself:
 *   - _redirects, _headers — copied as-is from static/, same as any other
 *     locale-duplicated static asset.
 *   - robots.txt — also from static/, but crawlers only ever request it at
 *     the true domain root (docs.bitrise.io/robots.txt), so a per-locale
 *     copy is invisible to them.
 *   - sitemap.xml — generated by the sitemap plugin. static/robots.txt
 *     itself declares `Sitemap: https://docs.bitrise.io/sitemap.xml`, so
 *     leaving this unpromoted breaks that declared discovery URL.
 *   - 404.html — generated by Docusaurus. Cloudflare Pages (like most
 *     static hosts) auto-serves a root-level 404.html for any unmatched
 *     path with a real 404 status, no _redirects rule required.
 * Without this step, all of the above would silently stop applying after
 * deploy (including the pre-existing legacy /jp/* redirect rule), even
 * though the build succeeds and looks correct locally.
 *
 * NOTE: index.html deliberately does NOT get promoted the same way. It was
 * tried and reverted — copying build/en/index.html to build/index.html
 * serves correct HTML on the initial request, but Docusaurus's client-side
 * router has no route registered for bare "/" (only /en/... and /ja/...),
 * so React hydration fails (errors #418/#423) and immediately replaces the
 * page with a client-rendered 404 for real browser users. A redirect
 * (see static/_redirects) happens at the HTTP layer before any JS runs,
 * so it doesn't hit this at all — that's why the root case is a redirect,
 * not a promoted file, unlike the files handled here. 404.html doesn't
 * have this problem: a hydration mismatch on an already-404 page still
 * ends up rendering "not found", which is the correct outcome either way.
 *
 * Every locale gets an identical copy of static/, so copying from any one
 * of them is equivalent — DEFAULT_LOCALE picks a deterministic source
 * rather than relying on directory-listing order.
 */
const fs = require('fs');
const path = require('path');

const BUILD_DIR = path.resolve(__dirname, '..', 'build');
const DEFAULT_LOCALE = 'en';
const FILES = ['_redirects', '_headers', 'robots.txt', 'sitemap.xml', '404.html'];

for (const file of FILES) {
  const src = path.join(BUILD_DIR, DEFAULT_LOCALE, file);
  const dest = path.join(BUILD_DIR, file);
  if (!fs.existsSync(src)) {
    console.log(`· ${src} not found, skipping`);
    continue;
  }
  fs.copyFileSync(src, dest);
  console.log(`✔ promoted ${file} to build root`);
}
