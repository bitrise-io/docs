#!/usr/bin/env node
/**
 * Copies the files that must stay addressable at the *domain root* up from
 * the default locale's per-locale output directory to the true build root.
 *
 * Since i18n.localeConfigs[locale].baseUrl gave each locale its own baseUrl
 * (see docusaurus.config.ts), Docusaurus's per-locale outDir became
 * build/<locale>/ — so everything that used to land at build/ (the whole of
 * static/, plus the generated sitemap.xml, the changelog feeds and the
 * docusaurus-plugin-llms output) now lands under build/en/ and build/ja/,
 * and nothing at all lands at build/ itself. Each file below is fetched by
 * something that can only ever look at the root:
 *   - _redirects, _headers — copied as-is from static/, same as any other
 *     locale-duplicated static asset. Cloudflare Pages only reads them from
 *     the deployed directory's root, so without this step every redirect
 *     rule (including the pre-existing legacy /jp/* one) silently stops
 *     applying after deploy.
 *   - robots.txt — also from static/, but crawlers only ever request it at
 *     the true domain root (docs.bitrise.io/robots.txt), so a per-locale
 *     copy is invisible to them.
 *   - sitemap.xml — generated by the sitemap plugin. static/robots.txt
 *     itself declares `Sitemap: https://docs.bitrise.io/sitemap.xml`, so
 *     leaving this unpromoted breaks that declared discovery URL.
 *   - 404.html — generated by Docusaurus. Cloudflare Pages (like most
 *     static hosts) auto-serves a root-level 404.html for any unmatched
 *     path with a real 404 status, no _redirects rule required.
 *   - llms.txt, llms-full.txt, and every .md file — the hand-curated
 *     AI-agent index (#114) is published at the root, and llms.txt itself
 *     documents the root `<page>.md` mirror URLs ("take the page path and
 *     append .md"). The mirrors are generated by docusaurus-plugin-llms into
 *     its outDir, so they moved with it; copying every .md keeps those
 *     public URLs alive (it also covers static/onboarding-for-agents.md,
 *     which has its own _headers Content-Type rule).
 *   - favicon.ico — browsers request /favicon.ico directly, regardless of
 *     the <link> in the page head.
 *   - changelog.xml, changelog.json — the docs changelog feeds
 *     (src/plugins/changelog-feed.ts). Their root URLs are load-bearing
 *     three times over: the feed names https://docs.bitrise.io/changelog.xml
 *     as its own rel="self", the changelog page's <link rel="alternate"> and
 *     Subscribe button point at /changelog.xml from raw JSX (so no baseUrl
 *     is applied), and existing subscribers cannot be migrated to a new URL.
 * Without this step, all of the above would silently break after deploy,
 * even though the build succeeds and looks correct locally.
 *
 * NOT promoted, deliberately:
 *
 *   index.html — tried and reverted. Copying build/en/index.html to
 *     build/index.html serves correct HTML on the initial request, but
 *     Docusaurus's client-side router has no route registered for bare "/"
 *     (only /en/... and /ja/...), so React hydration fails (errors
 *     #418/#423) and immediately replaces the page with a client-rendered
 *     404 for real browser users. A redirect (see static/_redirects) happens
 *     at the HTTP layer before any JS runs, so it never hits this — that's
 *     why the root case is a redirect, not a promoted file, unlike the files
 *     handled here. 404.html doesn't have this problem: verified by serving
 *     the generated page at a non-locale path, it hydrates into the branded
 *     "Page Not Found" with no console errors, which is the correct outcome
 *     either way.
 *
 *   img/, fonts/ — 1800+ files, ~184 MB, already duplicated per locale by
 *     the build. A third copy at the root would bloat every deploy for the
 *     sake of external hotlinks, so those two prefixes are 301'd to /en/ in
 *     static/_redirects instead.
 *
 * Every locale gets an identical copy of static/, so copying from any one
 * of them is equivalent — DEFAULT_LOCALE picks a deterministic source
 * rather than relying on directory-listing order.
 */
const fs = require('fs');
const path = require('path');

const BUILD_DIR = path.resolve(__dirname, '..', 'build');
const DEFAULT_LOCALE = 'en';
const LOCALE_DIR = path.join(BUILD_DIR, DEFAULT_LOCALE);

// Checked into static/, so a full build always emits these. A missing one
// means the locale output layout changed and the root surface is broken —
// fail rather than deploy a site whose /robots.txt 404s.
const REQUIRED_FILES = ['_redirects', '_headers', 'robots.txt', 'llms.txt', 'favicon.ico'];

// Plugin- or framework-generated. Still expected in a full `npm run build`,
// but a missing one means a plugin was reconfigured, not that the layout
// broke — warn.
const GENERATED_FILES = [
  'sitemap.xml',
  '404.html',
  'llms-full.txt',
  'changelog.xml',
  'changelog.json',
];

/** Copies every *.md under the locale dir to the root, preserving structure. */
function promoteMarkdownMirrors() {
  let count = 0;
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, {withFileTypes: true})) {
      const from = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        walk(from);
      } else if (entry.name.endsWith('.md')) {
        const dest = path.join(BUILD_DIR, path.relative(LOCALE_DIR, from));
        fs.mkdirSync(path.dirname(dest), {recursive: true});
        fs.copyFileSync(from, dest);
        count += 1;
      }
    }
  };
  walk(LOCALE_DIR);
  console.log(`✔ promoted ${count} .md mirror(s) to build root`);
}

if (!fs.existsSync(LOCALE_DIR)) {
  console.error(
    `✖ ${LOCALE_DIR} not found.\n` +
      `  The default locale's output is expected at build/${DEFAULT_LOCALE}/ ` +
      `(i18n.localeConfigs.${DEFAULT_LOCALE}.baseUrl in docusaurus.config.ts).\n` +
      `  If that changed, update DEFAULT_LOCALE here — otherwise the deploy ` +
      `has no root _redirects, robots.txt or llms.txt.`,
  );
  process.exit(1);
}

for (const file of REQUIRED_FILES) {
  const src = path.join(LOCALE_DIR, file);
  if (!fs.existsSync(src)) {
    console.error(
      `✖ ${src} not found. It is checked into static/, so its absence means ` +
        `the per-locale output layout changed. Fix this script before deploying.`,
    );
    process.exit(1);
  }
  fs.copyFileSync(src, path.join(BUILD_DIR, file));
  console.log(`✔ promoted ${file} to build root`);
}

for (const file of GENERATED_FILES) {
  const src = path.join(LOCALE_DIR, file);
  if (!fs.existsSync(src)) {
    console.log(`· ${file} not found in build/${DEFAULT_LOCALE}/, skipping`);
    continue;
  }
  fs.copyFileSync(src, path.join(BUILD_DIR, file));
  console.log(`✔ promoted ${file} to build root`);
}

promoteMarkdownMirrors();
