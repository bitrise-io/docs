#!/usr/bin/env node
/**
 * Guard: every documentation page has a non-empty `description` in its
 * frontmatter.
 *
 * Three things read that field, and each degrades silently without it:
 *
 *   - The social preview card (functions/og.js) is generated from `title` +
 *     `description`. A page without one falls back to the generic site tagline.
 *   - docusaurus-plugin-llms writes the description under the title of every
 *     generated .md mirror. Without one it makes do with the page's first
 *     paragraph and removes that paragraph from the body.
 *   - The post-build step that drops the description from the mirrors can only
 *     do so safely when every description comes from the frontmatter.
 *
 * This script fails the build on the day someone adds a page without one, with
 * a message that says what to write. See scripts/check-links-source.js and
 * scripts/check-partials-source.js for the sibling guards: same shape, same
 * no-dependency rule (Node built-ins only, so no npm install in CI).
 *
 * Scope: every .md and .mdx page under docs/, except the generated API reference
 * (`/api-reference/`), which is overwritten by `npm run gen-api-docs` and has
 * no .md mirror.
 *
 * Usage:
 *   node scripts/check-descriptions-source.js                  # scan docs/
 *   node scripts/check-descriptions-source.js path/to/a.mdx    # scan specific files
 *
 * Exit code is non-zero if any page has no description.
 */

'use strict';

const fs = require('fs');
const path = require('path');

const DOCS_DIR = path.join(__dirname, '..', 'docs');

// Rewritten wholesale by scripts/sync_mcp_docs.py.
const SYNCED_MCP_DIR = 'docs/bitrise-platform/ai/bitrise-mcp/';

function collectFiles(dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...collectFiles(full));
    else if (/\.mdx?$/.test(entry.name)) out.push(full);
  }
  return out;
}

/** Generated by `npm run gen-api-docs`; never hand-edited, never mirrored. */
function isGenerated(file) {
  return file.split(path.sep).includes('api-reference');
}

/**
 * Reads the `description` of a page. Returns `{ value }` with the text, or
 * `{ problem }` with why there is no usable one. Reads only the leading `---`
 * frontmatter block, and only a top-level `description:` key. Handles inline,
 * quoted, and block (`>` / `|`) values.
 *
 * scripts/strip-mirror-descriptions.js uses `value` too, so the gate and the
 * strip step agree on what a page's description is.
 */
function parseDescription(source) {
  const lines = source.replace(/\r\n/g, '\n').split('\n');

  if (lines[0].trim() !== '---') return { problem: 'has no frontmatter' };

  let end = -1;
  for (let i = 1; i < lines.length; i++) {
    if (lines[i].trim() === '---' || lines[i].trim() === '...') {
      end = i;
      break;
    }
  }
  if (end === -1) return { problem: 'has an unterminated frontmatter block' };

  for (let i = 1; i < end; i++) {
    const match = /^description\s*:\s*(.*)$/.exec(lines[i]);
    if (!match) continue;

    const inline = match[1].trim();
    const blockScalar = /^([>|])[+-]?\d*$/.exec(inline);

    if (inline !== '' && !blockScalar) {
      if (/^(""|''|~|null)$/.test(inline)) return { problem: 'has an empty `description`' };
      return { value: decodeScalar(inline) };
    }

    // `description: >` or a bare `description:`: the text is on the indented
    // lines that follow, up to the next top-level key.
    const body = [];
    for (let j = i + 1; j < end; j++) {
      if (lines[j].trim() === '') {
        body.push('');
        continue;
      }
      if (!/^\s/.test(lines[j])) break;
      body.push(lines[j].trim());
    }
    const text = body.join(blockScalar && blockScalar[1] === '|' ? '\n' : ' ').trim();
    return text === '' ? { problem: 'has an empty `description`' } : { value: text };
  }

  return { problem: 'has no `description`' };
}

/** Decodes a YAML inline scalar: double-quoted, single-quoted, or plain. */
function decodeScalar(raw) {
  if (raw.startsWith('"') && raw.endsWith('"') && raw.length >= 2) {
    try {
      return JSON.parse(raw);
    } catch {
      return raw.slice(1, -1);
    }
  }
  if (raw.startsWith("'") && raw.endsWith("'") && raw.length >= 2) {
    return raw.slice(1, -1).replace(/''/g, "'");
  }
  return raw;
}

/** Returns why the page has no usable description, or null when it has one. */
function descriptionProblem(source) {
  return parseDescription(source).problem || null;
}

function main() {
  const args = process.argv.slice(2);
  let files;

  if (args.length > 0) {
    files = args.map((f) => path.resolve(f));
  } else if (fs.existsSync(DOCS_DIR)) {
    files = collectFiles(DOCS_DIR);
  } else {
    console.error(`No docs directory at ${DOCS_DIR}`);
    process.exit(1);
  }

  files = files.filter((f) => !isGenerated(f));

  const problems = [];
  for (const file of files) {
    const problem = descriptionProblem(fs.readFileSync(file, 'utf8'));
    if (problem) problems.push({ file, problem });
  }

  const scanned = `${files.length} page${files.length === 1 ? '' : 's'}`;

  if (problems.length === 0) {
    console.log(`check-descriptions-source: ${scanned} scanned, all have a description.`);
    return;
  }

  console.error(
    `check-descriptions-source: ${problems.length} of ${scanned} ` +
      `${problems.length === 1 ? 'has' : 'have'} no usable description.\n`
  );

  for (const p of problems) {
    console.error(`  ${path.relative(process.cwd(), p.file)}`);
    console.error(`    ${p.problem}`);
  }

  // The MCP pages are rewritten by scripts/sync_mcp_docs.py, which rebuilds
  // their frontmatter on every run, so a description typed into the page is
  // overwritten. Say where it goes instead.
  if (problems.some((p) => p.file.split(path.sep).join('/').includes(SYNCED_MCP_DIR))) {
    console.error(
      `\nPages under ${SYNCED_MCP_DIR} are synced from bitrise-io/bitrise-mcp. ` +
        `Don't edit the page: add an entry for it to DESCRIPTIONS in ` +
        `scripts/sync_mcp_docs.py, then run \`python3 scripts/sync_mcp_docs.py\`.`
    );
  }

  console.error(
    `\nAdd a \`description\` to the page's frontmatter: one sentence, around 150 ` +
      `characters, that says what the page helps the reader do.\n` +
      `It becomes the social preview card text and the page summary in the ` +
      `generated .md mirror.\n\n` +
      `  ---\n` +
      `  title: "Running Xcode tests on Bitrise"\n` +
      `  description: "Configure the Xcode Test Step to run unit and UI tests on Bitrise."\n` +
      `  ---\n\n` +
      `Write it fresh: don't paste the page's first paragraph. ` +
      `docusaurus-plugin-llms removes a body paragraph that exactly matches the ` +
      `description, so a copied paragraph disappears from the .md mirror.`
  );

  process.exit(1);
}

if (require.main === module) {
  main();
}

module.exports = { parseDescription, collectFiles, isGenerated, DOCS_DIR };
